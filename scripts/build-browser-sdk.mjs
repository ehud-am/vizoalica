import { build } from 'esbuild';
import { copyFile, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const WORKER_SDK_MODULE = 'apps/ingest-worker/src/generated/browser-sdk.ts';

/** The module the Worker imports. CI rebuilds it and fails when the committed copy differs. */
function workerSdkModule(code) {
  return `// Generated by scripts/build-browser-sdk.mjs from packages/browser-sdk. Do not edit.\nexport const BROWSER_SDK = ${JSON.stringify(code)};\n`;
}

const common = {
  absWorkingDir: fileURLToPath(new URL('..', import.meta.url)),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2022'],
  minify: true,
  alias: {
    '@vizoalica/event-contracts': './packages/event-contracts/src/index.ts',
    '@vizoalica/privacy': './packages/privacy/src/index.ts'
  }
};

await Promise.all([
  build({
    ...common,
    entryPoints: ['packages/browser-sdk/src/embed.ts'],
    outfile: 'packages/browser-sdk/dist/vizoalica.js',
    banner: { js: '/* Vizoalica browser SDK */' }
  }),
  build({
    ...common,
    entryPoints: ['packages/browser-sdk/src/dynamic-loader.ts'],
    outfile: 'packages/browser-sdk/dist/vizoalica-loader.js',
    banner: { js: '/* Vizoalica dynamic configuration loader */' }
  })
]);
await copyFile(
  'packages/browser-sdk/dist/vizoalica-loader.js',
  'examples/cloudflare-pages/public/vizoalica-loader.js'
);
// The Worker serves the same SDK at /vizoalica.js, so a static website needs only a script tag.
await writeFile(
  WORKER_SDK_MODULE,
  workerSdkModule(await readFile('packages/browser-sdk/dist/vizoalica.js', 'utf8'))
);
console.log(
  'Built SDK and loader bundles; synchronized the Pages loader asset and the Worker SDK module'
);
