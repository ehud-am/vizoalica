// Generates the static geography reference data used by the console's Geography view:
//   apps/admin-web/src/geo/countries.ts   country code, numeric code, name, continent
//   apps/admin-web/src/geo/world-paths.ts SVG paths for a world map
// The console ships these files as-is, so it never fetches map data at runtime. The inputs are
// dev dependencies only: `world-atlas` (Natural Earth, public domain data; ISC package),
// `countries-list` (MIT: names and continents), `i18n-iso-countries` (MIT: ISO numeric codes),
// `topojson-client` and `d3-geo` (ISC). Re-run with `node scripts/generate-world-geo.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoNaturalEarth1, geoPath } from 'd3-geo';
import iso from 'i18n-iso-countries';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const countriesList = require('countries-list');
const outDir = new URL('../apps/admin-web/src/geo/', import.meta.url);
const header = (name) =>
  `// GENERATED by scripts/generate-world-geo.mjs. Do not edit; re-run the script instead.\n// ${name}\n`;

const WIDTH = 960;
const HEIGHT = 500;

const CONTINENTS = {
  AF: 'Africa',
  AN: 'Antarctica',
  AS: 'Asia',
  EU: 'Europe',
  NA: 'North America',
  OC: 'Oceania',
  SA: 'South America'
};

// Kosovo (XK) has no ISO numeric code, so it has a name and continent but no map shape.
const countries = Object.entries(countriesList.countries)
  .map(([code, country]) => ({
    code,
    numeric: iso.alpha2ToNumeric(code) ?? '',
    name: country.name,
    continent: CONTINENTS[country.continent]
  }))
  .sort((a, b) => a.code.localeCompare(b.code));

const countriesSource = `${header('Country reference data: code, ISO numeric code, common English name, continent.')}
export type Continent =
  | 'Africa'
  | 'Antarctica'
  | 'Asia'
  | 'Europe'
  | 'North America'
  | 'Oceania'
  | 'South America';

export interface CountryRecord {
  code: string;
  numeric: string;
  name: string;
  continent: Continent;
}

export const COUNTRIES: readonly CountryRecord[] = ${JSON.stringify(countries, null, 2)};
`;
writeFileSync(new URL('countries.ts', outDir), countriesSource);

const topology = JSON.parse(
  readFileSync(require.resolve('world-atlas/countries-110m.json'), 'utf8')
);
const world = feature(topology, topology.objects.countries);
const projection = geoNaturalEarth1().fitExtent(
  [
    [4, 4],
    [WIDTH - 4, HEIGHT - 4]
  ],
  { type: 'Sphere' }
);
const path = geoPath(projection).digits(1);
const shapes = world.features
  .filter((f) => f.id !== undefined && f.id !== '010') // Antarctica dominates the bottom edge
  .map((f) => ({ numeric: String(f.id).padStart(3, '0'), path: path(f) }))
  .filter((s) => s.path)
  .sort((a, b) => a.numeric.localeCompare(b.numeric));

const pathsSource = `${header('World map shapes (Natural Earth 110m), projected to a 960x500 viewBox.')}
export const WORLD_VIEWBOX = '0 0 ${WIDTH} ${HEIGHT}';

export const WORLD_OUTLINE = ${JSON.stringify(path({ type: 'Sphere' }))};

export interface MapShape {
  numeric: string;
  path: string;
}

export const WORLD_SHAPES: readonly MapShape[] = ${JSON.stringify(shapes, null, 2)};
`;
writeFileSync(new URL('world-paths.ts', outDir), pathsSource);
console.log(`countries: ${countries.length}, shapes: ${shapes.length}`);
